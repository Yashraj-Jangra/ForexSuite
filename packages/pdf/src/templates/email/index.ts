export function femaAlertEmailHtml(data: { invoiceNumber: string; customerName: string; daysSince: number; status: string }): string {
  const color = data.status === 'critical' ? '#ef4444' : '#f59e0b';
  return `<!DOCTYPE html><html><head><meta charset="utf-8"><style>
    body { font-family: -apple-system, sans-serif; padding: 24px; color: #1a1a2e; }
    .header { font-size: 22px; font-weight: 800; color: ${color}; margin-bottom: 16px; }
    .body-text { font-size: 14px; line-height: 1.6; }
    .alert-box { background: ${data.status === 'critical' ? '#fef2f2' : '#fffbeb'}; border-radius: 8px; padding: 16px; margin: 16px 0; }
  </style></head><body>
    <div class="header">FEMA Export Realization Alert</div>
    <p class="body-text">Invoice <strong>${data.invoiceNumber}</strong> for <strong>${data.customerName}</strong>.</p>
    <div class="alert-box"><strong>${data.daysSince} days</strong> since export — ${data.status === 'critical' ? 'CRITICAL: exceeds 240 days' : 'WARNING: approaching 270-day limit'}</div>
  </body></html>`;
}